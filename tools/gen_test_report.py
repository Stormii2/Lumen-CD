#!/usr/bin/env python3
"""Run tests/cases.py through the compiler and write docs/TEST_CASES.md (the
human-readable test-case + test-result table). Exit status 1 if any case fails."""
import os, sys
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT); sys.path.insert(0, os.path.join(ROOT, "tests"))
from cases import CASES                                  # noqa: E402
from lumen import compile_source, TACInterpreter, LumenRuntimeError   # noqa: E402

NAMES = {"valid": "Valid inputs", "invalid": "Invalid inputs (one defect each)",
         "boundary": "Boundary cases", "recovery": "Error conditions and recovery",
         "complex": "Complex inputs"}


def snippet(src, n=70):
    s = src.replace("\n", " ⏎ ")
    return (s[:n] + "...") if len(s) > n else s


def execute(c):
    res = compile_source(c["src"])
    codes = [d.code for d in res.diagnostics]
    if "codes" in c:
        return codes == c["codes"], "diagnostics: " + (", ".join(codes) or "none")
    if not res.ok or codes != c.get("warn", []):
        return False, "diagnostics: " + ", ".join(codes)
    try:
        out = TACInterpreter(res.functions).run()
    except LumenRuntimeError as e:
        return ("rt" in c and e.code == c["rt"]), f"run-time error {e.code}"
    return ("out" in c and out == c["out"]), "output: " + (" | ".join(out) if out else "(none)")


def expected(c):
    if "codes" in c:
        return "diagnostics: " + ", ".join(c["codes"])
    if "rt" in c:
        return "run-time error " + c["rt"] + (f" (+ warning {', '.join(c['warn'])})" if "warn" in c else "")
    return "output: " + (" | ".join(c["out"]) if c["out"] else "(none)")


def main():
    rows, per = [], {}
    for c in CASES:
        ok, actual = execute(c)
        rows.append((c, ok, actual))
        t = per.setdefault(c["cat"], [0, 0]); t[0] += 1; t[1] += ok
    L = ["# Test cases and results\n",
         "Generated by `tools/gen_test_report.py` from `tests/cases.py` - the same table the pytest suite runs. "
         "Every row is executed through the real pipeline (lex, parse, check, TAC, interpret).\n",
         "| category | cases | passed |", "|---|---|---|"]
    for k, (n, p) in per.items():
        L.append(f"| {NAMES[k]} | {n} | {p} |")
    tn, tp = sum(v[0] for v in per.values()), sum(v[1] for v in per.values())
    L.append(f"| **total** | **{tn}** | **{tp}** |\n")
    cur = None
    for c, ok, actual in rows:
        if c["cat"] != cur:
            cur = c["cat"]
            L += [f"\n## {NAMES[cur]}\n", "| ID | purpose | input | expected | actual | result |", "|---|---|---|---|---|---|"]
        L.append("| {id} | {d} | `{s}` | {e} | {a} | {r} |".format(
            id=c["id"], d=c["desc"], s=snippet(c["src"]).replace("|", "\\|"), e=expected(c).replace("|", "\\|"),
            a=actual.replace("|", "\\|"), r="PASS" if ok else "**FAIL**"))
    out = os.path.join(ROOT, "docs", "TEST_CASES.md")
    with open(out, "w", encoding="utf-8") as f:
        f.write("\n".join(L) + "\n")
    print(f"{tp}/{tn} cases pass -> {out}")
    return 0 if tp == tn else 1


if __name__ == "__main__":
    sys.exit(main())
